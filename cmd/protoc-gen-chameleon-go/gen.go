// generate is the protogen entry point invoked once per protoc run.
func generate(p *protogen.Plugin) error {
	for _, f := range p.Files {
		if !f.Generate {
			continue
		}
		sites := findSecretSites(f)
		if len(sites) == 0 {
			continue
		}
		if err := generateSidecar(p, f, sites); err != nil {
			return err
		}
	}
	return nil
}

// generateSidecar emits one <basename>.chameleon.go per file with at
// least one Secret site. The plugin emits *secret.Map parameters
// (not value Map): secret.Map is a struct holding a sync.Mutex, so
// passing by value would copy the lock and break thread safety.
func generateSidecar(p *protogen.Plugin, f *protogen.File, sites []secretSite) error {
	filename := f.GeneratedFilenamePrefix + ".chameleon.go"
	gf := p.NewGeneratedFile(filename, f.GoImportPath)

	gf.P("// Code generated by protoc-gen-chameleon-go. DO NOT EDIT.")
	gf.P("// source: ", f.Desc.Path())
	gf.P()
	gf.P("package ", f.GoPackageName)
	gf.P()

	secretIdent := protogen.GoImportPath(pluginState.secretPkg).Ident("Secret")
	mapIdent := protogen.GoImportPath(pluginState.secretPkg).Ident("Map")
	strconvPkg := protogen.GoImportPath("strconv")

	gf.P("// Functions below resolve typed accessors against a")
	gf.P("// secret.Map (typically Resolution.Secrets from the chameleon")
	gf.P("// resolver). Function names encode the dotted PXF path the")
	gf.P("// chameleon parse.Move walker assigns; renaming a field in")
	gf.P("// .proto produces a new function name and stale call-sites")
	gf.P("// fail to compile.")
	gf.P()

	for _, s := range sites {
		emitSiteFunc(gf, s, secretIdent, mapIdent, strconvPkg)
		gf.P()
	}

	if pluginState.withResolved {
		emitResolvedWrappers(gf, sites, secretIdent, mapIdent, strconvPkg)
	}
	return nil
}

// funcParam describes one parameter of a generated accessor:
// the index into a repeated container, or the key into a map.
type funcParam struct {
	Name    string            // "i", "key", "key2", etc.
	GoType  string            // "int", "string", "int32", etc.
	Step    int               // index into secretSite.Path
	KeyKind protoreflect.Kind // for map params
}

// assignParams walks the path and produces one param per non-scalar
// step, in path order. Repeated containers get i, j, k, l, i4, i5...
// Map containers get key, key2, key3...
func assignParams(path []pathStep) []funcParam {
	var ps []funcParam
	repeatedCount := 0
	mapCount := 0
	for i, step := range path {
		switch step.Container {
		case containerRepeated:
			ps = append(ps, funcParam{
				Name:   repeatedParamName(repeatedCount),
				GoType: "int",
				Step:   i,
			})
			repeatedCount++
		case containerMap:
			ps = append(ps, funcParam{
				Name:    mapParamName(mapCount),
				GoType:  goTypeForMapKey(step.MapKeyKind),
				Step:    i,
				KeyKind: step.MapKeyKind,
			})
			mapCount++
		}
	}
	return ps
}

func repeatedParamName(n int) string {
	switch n {
	case 0:
		return "i"
	case 1:
		return "j"
	case 2:
		return "k"
	case 3:
		return "l"
	default:
		return fmt.Sprintf("i%d", n)
	}
}

func mapParamName(n int) string {
	if n == 0 {
		return "key"
	}
	return fmt.Sprintf("key%d", n+1)
}

func goTypeForMapKey(k protoreflect.Kind) string {
	switch k {
	case protoreflect.StringKind:
		return "string"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "uint64"
	case protoreflect.BoolKind:
		return "bool"
	default:
		return "string"
	}
}

// pathFragment is one piece of the runtime path expression. A static
// fragment is a Go string literal (already quoted). A param fragment
// is a Go expression that converts a parameter to its path-segment
// string at runtime.
type pathFragment struct {
	IsParam bool
	Static  string    // Go source, with quotes — emitted verbatim.
	Param   funcParam // for runtime-expr fragments
}

// buildPathFragments walks path + params and produces the list of
// fragments whose `+`-concatenation IS the runtime path string the
// chameleon parse.Move walker emitted at resolve time. Fragments
// alternate static / runtime-expr / static.
func buildPathFragments(path []pathStep, params []funcParam) []pathFragment {
	var frags []pathFragment
	var staticBuf strings.Builder
	pIdx := 0

	flushStatic := func() {
		if staticBuf.Len() > 0 {
			frags = append(frags, pathFragment{Static: strconv.Quote(staticBuf.String())})
			staticBuf.Reset()
		}
	}

	for i, step := range path {
		if i > 0 {
			staticBuf.WriteString(".")
		}
		staticBuf.WriteString(step.Name)
		if step.Container == containerScalar {
			continue
		}
		// Container: emit `[`, runtime-expr, `]`.
		staticBuf.WriteByte('[')
		flushStatic()
		frags = append(frags, pathFragment{IsParam: true, Param: params[pIdx]})
		pIdx++
		staticBuf.WriteByte(']')
	}
	flushStatic()
	return frags
}

// emitSiteFunc writes one accessor function for the given site.
func emitSiteFunc(gf *protogen.GeneratedFile, s secretSite, secretIdent, mapIdent protogen.GoIdent, strconvPkg protogen.GoImportPath) {
	funcName := siteFuncName(s)
	params := assignParams(s.Path)
	frags := buildPathFragments(s.Path, params)
	docPath := dottedPath(s.Path)

	// Signature.
	signature := buildSignature(funcName, params)
	gf.P("// ", funcName, " returns the *secret.Secret reachable at PXF path ", strconv.Quote(docPath), ",")
	gf.P("// or nil if absent or destroyed.")
	gf.P("func ", signature, "(s *", mapIdent, ", ", paramsList(params), ") *", secretIdent, " {")

	// Body: build the runtime path expression and call s.Get().
	emitGetCall(gf, frags, strconvPkg)
	gf.P("}")
}

// buildSignature returns just the function name (parameters are
// emitted separately so we can interleave the *secret.Map ident).
func buildSignature(name string, _ []funcParam) string {
	return name
}

// paramsList renders the variadic typed-param list (after `s *Map`).
func paramsList(params []funcParam) string {
	if len(params) == 0 {
		return ""
	}
	var b strings.Builder
	for i, p := range params {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(p.Name)
		b.WriteByte(' ')
		b.WriteString(p.GoType)
	}
	return b.String()
}

// emitGetCall renders `return s.Get(<expr>)` where <expr> is the
// fragment-concatenation. Param fragments emit the appropriate
// strconv call for their type.
func emitGetCall(gf *protogen.GeneratedFile, frags []pathFragment, strconvPkg protogen.GoImportPath) {
	gf.P("\treturn s.Get(", joinFragmentRefs(gf, frags, strconvPkg), ")")
}

// joinFragmentRefs returns a single Go expression — the `+`-joined
// fragment list. We can't use string concatenation at codegen time
// because runtime-expr fragments contain GoIdent values that the
// protogen.GeneratedFile resolves later. Instead we let GeneratedFile
// build the expression by writing each piece with QualifiedGoIdent.
//
// This function returns the expression as a slice of arguments to
// gf.P; protogen handles the joining and import management.
func joinFragmentRefs(gf *protogen.GeneratedFile, frags []pathFragment, strconvPkg protogen.GoImportPath) string {
	// We need to inline the strconv calls. Since gf.P stringifies its
	// args (with QualifiedGoIdent for GoIdent values) and emits them
	// space-joined, we build the expression as a single string so
	// nothing space-pads the operators.
	var b strings.Builder
	for i, fr := range frags {
		if i > 0 {
			b.WriteString(" + ")
		}
		if !fr.IsParam {
			b.WriteString(fr.Static)
			continue
		}
		switch fr.Param.KeyKind {
		case protoreflect.StringKind:
			b.WriteString(gf.QualifiedGoIdent(strconvPkg.Ident("Quote")))
			b.WriteByte('(')
			b.WriteString(fr.Param.Name)
			b.WriteByte(')')
		case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
			b.WriteString(gf.QualifiedGoIdent(strconvPkg.Ident("FormatInt")))
			b.WriteString("(int64(")
			b.WriteString(fr.Param.Name)
			b.WriteString("), 10)")
		case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
			b.WriteString(gf.QualifiedGoIdent(strconvPkg.Ident("FormatInt")))
			b.WriteString("(")
			b.WriteString(fr.Param.Name)
			b.WriteString(", 10)")
		case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
			b.WriteString(gf.QualifiedGoIdent(strconvPkg.Ident("FormatUint")))
			b.WriteString("(uint64(")
			b.WriteString(fr.Param.Name)
			b.WriteString("), 10)")
		case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
			b.WriteString(gf.QualifiedGoIdent(strconvPkg.Ident("FormatUint")))
			b.WriteString("(")
			b.WriteString(fr.Param.Name)
			b.WriteString(", 10)")
		case protoreflect.BoolKind:
			b.WriteString(gf.QualifiedGoIdent(strconvPkg.Ident("FormatBool")))
			b.WriteByte('(')
			b.WriteString(fr.Param.Name)
			b.WriteByte(')')
		default:
			// Repeated index (no map kind) defaults to int.
			b.WriteString(gf.QualifiedGoIdent(strconvPkg.Ident("Itoa")))
			b.WriteByte('(')
			b.WriteString(fr.Param.Name)
			b.WriteByte(')')
		}
	}
	return b.String()
}

// siteFuncName builds the public function name from the site's root
// message and path. Convention: <RootName>Secret_<Path> with each
// path segment converted from snake_case to PascalCase and joined by
// underscores. Container kind doesn't affect the name — the
// parameter list distinguishes scalar/repeated/map.
func siteFuncName(s secretSite) string {
	var b strings.Builder
	b.WriteString(s.Root.GoIdent.GoName)
	b.WriteString("Secret_")
	for i, step := range s.Path {
		if i > 0 {
			b.WriteByte('_')
		}
		b.WriteString(toCamel(step.Name))
	}
	return b.String()
}

// dottedPath returns the path in PXF dotted form for godoc. Container
// segments include `[i]` / `[key]` markers so the doc reads the same
// way the runtime path does.
func dottedPath(path []pathStep) string {
	var b strings.Builder
	repeatedCount := 0
	mapCount := 0
	for i, step := range path {
		if i > 0 {
			b.WriteByte('.')
		}
		b.WriteString(step.Name)
		switch step.Container {
		case containerRepeated:
			b.WriteByte('[')
			b.WriteString(repeatedParamName(repeatedCount))
			b.WriteByte(']')
			repeatedCount++
		case containerMap:
			b.WriteByte('[')
			b.WriteString(mapParamName(mapCount))
			b.WriteByte(']')
			mapCount++
		}
	}
	return b.String()
}

// toCamel converts a snake_case proto field name to PascalCase.
func toCamel(s string) string {
	var b strings.Builder
	upNext := true
	for _, r := range s {
		if r == '_' {
			upNext = true
			continue
		}
		if upNext {
			if r >= 'a' && r <= 'z' {
				r -= 'a' - 'A'
			}
			upNext = false
		}
		b.WriteRune(r)
	}
	return b.String()
}
